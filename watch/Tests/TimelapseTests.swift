        let url = FileManager.default.temporaryDirectory.appending(path: "test-\(UUID().uuidString).mov")
        try Self.movie.write(to: url)
        return url
    }

    func testIndex() throws {
        let url = try file()
        defer { try? FileManager.default.removeItem(at: url) }
        let m = try MovieIndex(url: url)
        XCTAssertEqual(m.width, 32)
        XCTAssertEqual(m.height, 24)
        XCTAssertEqual(m.fps, 5)
        XCTAssertEqual(m.count, 11)
        // Each frame is a JPEG.
        for i in 0..<m.count {
            let d = Self.movie.subdata(in: Int(m.offsets[i])..<Int(m.offsets[i]) + m.sizes[i])
            XCTAssertEqual(Array(d.prefix(2)), [0xFF, 0xD8], "frame \(i)")
        }
    }

    func testBadFile() throws {
        let url = FileManager.default.temporaryDirectory.appending(path: "bad-\(UUID().uuidString).mov")
        try Data(Self.movie.prefix(500)).write(to: url)
        defer { try? FileManager.default.removeItem(at: url) }
        XCTAssertThrowsError(try MovieIndex(url: url))
    }

    func testConvert() async throws {
        let src = try file()
        let dst = FileManager.default.temporaryDirectory.appending(path: "test-\(UUID().uuidString).mp4")
        defer {
            try? FileManager.default.removeItem(at: src)
            try? FileManager.default.removeItem(at: dst)
        }
        try await Timelapse.convert(src, to: dst)
        let asset = AVURLAsset(url: dst)
        let tracks = try await asset.loadTracks(withMediaType: .video)
        XCTAssertEqual(tracks.count, 1)
        let size = try await tracks[0].load(.naturalSize)
        XCTAssertEqual(size, CGSize(width: 32, height: 24))
        let length = try await asset.load(.duration).seconds
        XCTAssertEqual(length, 11.0 / 5, accuracy: 0.25)
        let playable = try await asset.load(.isPlayable)
        XCTAssertTrue(playable)
    }
