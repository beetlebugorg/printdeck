// icon draws an icon at x, y, scale pixels for each pixel of the icon. An unknown name is a dot.
func (c *canvas) icon(name string, x, y, scale int) {
	art, ok := icons[name]
	if !ok {
		art = icons["item"]
	}
	for dy, row := range art {
		for dx, ch := range row {
			if ch == '#' {
				c.fill(x+dx*scale, y+dy*scale, x+(dx+1)*scale, y+(dy+1)*scale, true)
			}
		}
	}
}
