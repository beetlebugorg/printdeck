// tinyDot reports the dot at column x and row y of a text in the small font.
func tinyDot(s string, x, y int) bool {
	ch, col := x/tinyAdvance, x%tinyAdvance
	if x < 0 || col == 3 || ch >= len(s) || y < 0 || y >= tinyRows {
		return false
	}
	g, ok := tinyFont[s[ch]]
	return ok && g[y][col] == '#'
}
