// Package gcodemeta reads what a slicer writes about a G-code file: the print time, the filament,
// the layer height, the temperatures, the material, the slicer and the thumbnail. It reads only the
// start and the end of the file, where the slicers put these comments.
package gcodemeta

import (
	"bufio"
	"bytes"
	"encoding/base64"
	"image"
	"image/jpeg"
	"image/png"
	"io"
	"os"
	"regexp"
	"strconv"
	"strings"
	"sync"
	"time"
)

// Meta is what the slicer wrote. A zero value means that the file does not say.
type Meta struct {
	Slicer      string        // for example "OrcaSlicer 2.3.0"
	PrintTime   time.Duration // the estimate of the slicer
	FilamentMM  float64
	FilamentG   float64
	LayerHeight float64 // mm
	NozzleTemp  int
	BedTemp     int
	Material    string // for example "PLA"
	// MaterialName is the material that the slicer chose, for example "Black ABS", or "". The
	// Printdeck plugin for Cura writes it.
	MaterialName string
	// Color is the color of the filament, for example "#1f2a5a", or "". PrusaSlicer, OrcaSlicer and
	// the Printdeck plugin for Cura write it.
	Color     string
	Thumbnail image.Image
}

// The slicers write the thumbnails at the start, and PrusaSlicer, OrcaSlicer and Bambu Studio write
// their settings and statistics at the end.
const (
	headSize = 512 << 10
	tailSize = 96 << 10
)

// Read reads the comments of a G-code file.
func Read(path string) (Meta, error) {
	f, err := os.Open(path)
	if err != nil {
		return Meta{}, err
	}
	defer f.Close()
	fi, err := f.Stat()
	if err != nil {
		return Meta{}, err
	}
	return Parse(f, fi.Size())
}

// Parse reads the comments of a G-code file of size bytes.
func Parse(r io.ReaderAt, size int64) (Meta, error) {
	head := make([]byte, min(size, headSize))
	if _, err := r.ReadAt(head, 0); err != nil && err != io.EOF {
		return Meta{}, err
	}
	var tail []byte
	if size > headSize {
		tail = make([]byte, min(size-headSize, tailSize))
		if _, err := r.ReadAt(tail, size-int64(len(tail))); err != nil && err != io.EOF {
			return Meta{}, err
		}
	}
	var p parser
	p.Thumbnail = thumbnail(head)
	// The head first: in a small file the tail is in the head too, and the end wins.
	for _, part := range [][]byte{head, tail} {
		s := bufio.NewScanner(bytes.NewReader(part))
		s.Buffer(make([]byte, 64<<10), 1<<20)
		for s.Scan() {
			p.line(s.Text())
		}
	}
	// The temperatures of the commands, when no comment gave them.
	if p.NozzleTemp == 0 {
		p.NozzleTemp = p.cmdNozzle
	}
	if p.BedTemp == 0 {
		p.BedTemp = p.cmdBed
	}
	return p.Meta, nil
}

// parser is a Meta while it is read, with the temperatures of the first commands.
type parser struct {
	Meta
	cmdNozzle, cmdBed int
}

var (
	// "; key = value" of PrusaSlicer, OrcaSlicer and Bambu Studio
	keyValue = regexp.MustCompile(`^;\s*([^=:]+?)\s*[=:]\s*(.+?)\s*$`)
	// "1d 2h 3m 4s"
	timeParts = regexp.MustCompile(`(\d+)\s*([dhms])`)
)

func (m *parser) line(l string) {
	if !strings.HasPrefix(l, ";") {
		m.command(l)
		return
	}
	// Cura
	switch {
	case strings.HasPrefix(l, ";TIME:"):
		if s, err := strconv.Atoi(strings.TrimSpace(l[6:])); err == nil {
			m.PrintTime = time.Duration(s) * time.Second
		}
		return
	case strings.HasPrefix(l, ";Filament used:"):
		v := strings.TrimSuffix(strings.TrimSpace(l[15:]), "m")
		if f, err := strconv.ParseFloat(strings.Split(v, ",")[0], 64); err == nil {
			m.FilamentMM = f * 1000
		}
		return
	case strings.HasPrefix(l, ";Layer height:"):
		m.LayerHeight = number(l[14:])
		return
	case strings.HasPrefix(l, ";Generated with "):
		m.Slicer = strings.Replace(strings.TrimSpace(l[16:]), "Cura_SteamEngine", "Cura", 1)
		return
	}
	if v, ok := strings.CutPrefix(l, "; generated by "); ok {
		if i := strings.Index(v, " on "); i > 0 {
			v = v[:i]
		}
		m.Slicer = strings.TrimSpace(v)
		return
	}
	kv := keyValue.FindStringSubmatch(l)
	if kv == nil {
		return
	}
	key, val := strings.ToLower(kv[1]), kv[2]
	switch key {
	case "estimated printing time (normal mode)", "total estimated time":
		m.PrintTime = parseTime(val)
	case "filament used [mm]":
		m.FilamentMM = sum(val)
	case "filament used [g]", "total filament weight [g]":
		m.FilamentG = sum(val)
	case "layer_height":
		m.LayerHeight = number(val)
	case "temperature", "nozzle_temperature":
		m.NozzleTemp = int(number(val))
	case "bed_temperature", "hot_plate_temp", "textured_plate_temp":
		if m.BedTemp == 0 || key == "bed_temperature" || key == "hot_plate_temp" {
			m.BedTemp = int(number(val))
		}
	case "filament_type":
		m.Material = strings.Split(strings.Trim(val, `"`), ";")[0]
	case "printdeck_material": // the Printdeck plugin for Cura
		m.Material = val
	case "printdeck_material_name":
		m.MaterialName = val
	case "printdeck_color":
		m.Color = val
	case "filament_colour":
		if m.Color == "" {
			m.Color = strings.Split(strings.Trim(val, `"`), ";")[0]
		}
	}
}

// command reads the temperatures from the first commands that set them, for a slicer that writes
// them in no comment (Cura): the parameters of the start macro (PRINT_START BED=60 EXTRUDER=230),
// or the first M104, M109, M140 or M190 with a temperature above 0. A comment of the slicer wins.
func (m *parser) command(l string) {
	if i := strings.IndexByte(l, ';'); i >= 0 {
		l = l[:i]
	}
	f := strings.Fields(strings.ToUpper(l))
	if len(f) < 2 {
		return
	}
	param := func(names ...string) int {
		for _, p := range f[1:] {
			k, v, ok := strings.Cut(p, "=")
			if !ok {
				continue
			}
			for _, n := range names {
				if k == n {
					t, _ := strconv.ParseFloat(v, 64)
					return int(t)
				}
			}
		}
		return 0
	}
	s := func() int {
		for _, p := range f[1:] {
			if v, ok := strings.CutPrefix(p, "S"); ok {
				t, _ := strconv.ParseFloat(v, 64)
				return int(t)
			}
		}
		return 0
	}
	switch f[0] {
	case "PRINT_START", "START_PRINT":
		if t := param("EXTRUDER", "EXTRUDER_TEMP", "HOTEND", "NOZZLE"); t > 0 && m.cmdNozzle == 0 {
			m.cmdNozzle = t
		}
		if t := param("BED", "BED_TEMP"); t > 0 && m.cmdBed == 0 {
			m.cmdBed = t
		}
	case "M104", "M109":
		if t := s(); t > 0 && m.cmdNozzle == 0 {
			m.cmdNozzle = t
		}
	case "M140", "M190":
		if t := s(); t > 0 && m.cmdBed == 0 {
			m.cmdBed = t
		}
	}
}

// parseTime reads "1d 2h 3m 4s", or a number of seconds.
func parseTime(s string) time.Duration {
	var d time.Duration
	for _, p := range timeParts.FindAllStringSubmatch(s, -1) {
		n, _ := strconv.Atoi(p[1])
		d += time.Duration(n) * map[string]time.Duration{"d": 24 * time.Hour, "h": time.Hour, "m": time.Minute, "s": time.Second}[p[2]]
	}
	if d == 0 {
		if n, err := strconv.Atoi(strings.TrimSpace(s)); err == nil {
			d = time.Duration(n) * time.Second
		}
	}
	return d
}

// number reads the first number of a value, for example "0.2" or "210,210".
func number(s string) float64 {
	s = strings.TrimSpace(s)
	if i := strings.IndexAny(s, ",;"); i >= 0 {
		s = s[:i]
	}
	f, _ := strconv.ParseFloat(strings.TrimSpace(s), 64)
	return f
}

// sum adds a list of values, for example "12.3, 0.0" of two extruders.
func sum(s string) float64 {
	var t float64
	for _, p := range strings.FieldsFunc(s, func(r rune) bool { return r == ',' || r == ';' }) {
		f, _ := strconv.ParseFloat(strings.TrimSpace(p), 64)
		t += f
	}
	return t
}

// thumbnail decodes the largest PNG or JPEG thumbnail of the head:
//
//	; thumbnail begin 300x300 12345      (or thumbnail_PNG, thumbnail_JPG)
//	; iVBORw0KGgo...
//	; thumbnail end
func thumbnail(head []byte) image.Image {
	var best image.Image
	bestArea := 0
	s := bufio.NewScanner(bytes.NewReader(head))
	s.Buffer(make([]byte, 64<<10), 1<<20)
	var data strings.Builder
	in, kind, area := false, "", 0
	for s.Scan() {
		l := strings.TrimSpace(s.Text())
		switch {
		case !in && strings.HasPrefix(l, "; thumbnail") && strings.Contains(l, " begin "):
			f := strings.Fields(l)
			kind, area = f[1], 0
			if len(f) >= 4 {
				if w, h, ok := strings.Cut(f[3], "x"); ok {
					wi, _ := strconv.Atoi(w)
					hi, _ := strconv.Atoi(h)
					area = wi * hi
				}
			}
			in = true
			data.Reset()
		case in && strings.HasPrefix(l, "; thumbnail") && strings.HasSuffix(l, " end"):
			in = false
			if area <= bestArea || kind == "thumbnail_QOI" {
				continue
			}
			raw, err := base64.StdEncoding.DecodeString(data.String())
			if err != nil {
				continue
			}
			var img image.Image
			if kind == "thumbnail_JPG" {
				img, err = jpeg.Decode(bytes.NewReader(raw))
			} else {
				img, err = png.Decode(bytes.NewReader(raw))
			}
			if err == nil {
				best, bestArea = img, area
			}
		case in:
			data.WriteString(strings.TrimSpace(strings.TrimPrefix(l, ";")))
		}
	}
	return best
}

// Cache keeps the Meta of each file, by its path and its time of change.
type Cache struct {
	mu    sync.Mutex
	items map[string]cached
}

type cached struct {
	mod  time.Time
	meta Meta
}

// Get returns the Meta of a file, and reads it the first time and after a change.
func (c *Cache) Get(path string) Meta {
	fi, err := os.Stat(path)
	if err != nil {
		return Meta{}
	}
	c.mu.Lock()
	if it, ok := c.items[path]; ok && it.mod.Equal(fi.ModTime()) {
		c.mu.Unlock()
		return it.meta
	}
	c.mu.Unlock()
	m, _ := Read(path)
	c.mu.Lock()
	if c.items == nil {
		c.items = map[string]cached{}
	}
	c.items[path] = cached{fi.ModTime(), m}
	c.mu.Unlock()
	return m
}
