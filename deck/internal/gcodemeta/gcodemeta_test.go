// The start and the end of a file of Cura 5.13 for the test printer.
func TestCura(t *testing.T) {
	m, err := Read("testdata/cura.gcode")
	if err != nil {
		t.Fatal(err)
	}
	want := Meta{Slicer: "Cura 5.13.0", PrintTime: 2041 * time.Second, FilamentMM: 723.506, LayerHeight: 0.25,
		NozzleTemp: 230, BedTemp: 60}
	if m != want {
		t.Errorf("got  %+v\nwant %+v", m, want)
	}
}

// A file in the form of OrcaSlicer: two thumbnails at the start, the statistics and the settings at
// the end, after more than the head.
func TestOrca(t *testing.T) {
	var b bytes.Buffer
	b.WriteString("; HEADER_BLOCK_START\n; generated by OrcaSlicer 2.3.0 on 2026-10-20 at 14:02:11\n")
	b.WriteString("; total estimated time: 1h 45m 10s\n; HEADER_BLOCK_END\n")
	for _, size := range []int{16, 64} {
		img := image.NewRGBA(image.Rect(0, 0, size, size))
		img.Set(1, 1, color.RGBA{255, 0, 0, 255})
		var p bytes.Buffer
		png.Encode(&p, img)
		enc := base64.StdEncoding.EncodeToString(p.Bytes())
		fmt.Fprintf(&b, "; thumbnail begin %dx%d %d\n", size, size, len(enc))
		for i := 0; i < len(enc); i += 78 {
			fmt.Fprintf(&b, "; %s\n", enc[i:min(len(enc), i+78)])
		}
		b.WriteString("; thumbnail end\n")
	}
	b.WriteString("M190 S55\nM109 S205\n")
	for b.Len() < 700<<10 {
		b.WriteString("G1 X10.000 Y10.000 E0.01234\n")
	}
	b.WriteString("; filament used [mm] = 4100.12\n; filament used [g] = 12.30\n")
	b.WriteString("; estimated printing time (normal mode) = 1h 42m 3s\n")
	b.WriteString("; CONFIG_BLOCK_START\n; filament_type = PLA\n; hot_plate_temp = 60\n; layer_height = 0.2\n")
	b.WriteString("; nozzle_temperature = 210\n; CONFIG_BLOCK_END\n")
	m, err := Parse(bytes.NewReader(b.Bytes()), int64(b.Len()))
	if err != nil {
		t.Fatal(err)
	}
	if m.Thumbnail == nil || m.Thumbnail.Bounds().Dx() != 64 {
		t.Errorf("thumbnail %v, want the 64x64 one", m.Thumbnail)
	}
	m.Thumbnail = nil
	want := Meta{Slicer: "OrcaSlicer 2.3.0", PrintTime: time.Hour + 42*time.Minute + 3*time.Second, FilamentMM: 4100.12,
		FilamentG: 12.3, LayerHeight: 0.2, NozzleTemp: 210, BedTemp: 60, Material: "PLA"}
	if m != want {
		t.Errorf("got  %+v\nwant %+v", m, want)
	}
}

func TestParseTime(t *testing.T) {
	for s, want := range map[string]time.Duration{"1d 2h 3m 4s": 26*time.Hour + 3*time.Minute + 4*time.Second,
		"42m 3s": 42*time.Minute + 3*time.Second, "6123": 6123 * time.Second, "": 0} {
		if got := parseTime(s); got != want {
			t.Errorf("parseTime(%q) = %v, want %v", s, got, want)
		}
	}
}

func TestNoComments(t *testing.T) {
	m, err := Parse(strings.NewReader("G28\nG1 X1\n"), 9)
	if err != nil || m != (Meta{}) {
		t.Errorf("%+v, %v", m, err)
	}
}
