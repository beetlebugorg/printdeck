package screws_tilt_adjust

import "testing"

// The turns of Klipper's probe_finalize (screws_tilt_adjust.py) for some height differences and
// each thread.
func TestScrewAdjust(t *testing.T) {
	cases := []struct {
		diff           float64
		thread         int
		sign           string
		turns, minutes int64
	}{
		{0.0004, 0, "CW", 0, 0},
		{0.0004, 1, "CCW", 0, 0},
		{0.0004, 2, "CW", 0, 0},
		{0.0004, 3, "CCW", 0, 0},
		{0.0004, 4, "CW", 0, 0},
		{0.0004, 5, "CCW", 0, 0},
		{0.0004, 6, "CW", 0, 0},
		{0.0004, 7, "CCW", 0, 0},
		{0.05, 0, "CW", 0, 6},
		{0.05, 1, "CCW", 0, 6},
		{0.05, 2, "CW", 0, 4},
		{0.05, 3, "CCW", 0, 4},
		{0.05, 4, "CW", 0, 4},
		{0.05, 5, "CCW", 0, 4},
		{0.05, 6, "CW", 0, 3},
		{0.05, 7, "CCW", 0, 3},
		{-0.05, 0, "CCW", 0, 6},
		{-0.05, 1, "CW", 0, 6},
		{-0.05, 2, "CCW", 0, 4},
		{-0.05, 3, "CW", 0, 4},
		{-0.05, 4, "CCW", 0, 4},
		{-0.05, 5, "CW", 0, 4},
		{-0.05, 6, "CCW", 0, 3},
		{-0.05, 7, "CW", 0, 3},
		{0.123456, 0, "CW", 0, 15},
		{0.123456, 1, "CCW", 0, 15},
		{0.123456, 2, "CW", 0, 11},
		{0.123456, 3, "CCW", 0, 11},
		{0.123456, 4, "CW", 0, 9},
		{0.123456, 5, "CCW", 0, 9},
		{0.123456, 6, "CW", 0, 7},
		{0.123456, 7, "CCW", 0, 7},
		{-0.7071, 0, "CCW", 1, 25},
		{-0.7071, 1, "CW", 1, 25},
		{-0.7071, 2, "CCW", 1, 1},
		{-0.7071, 3, "CW", 1, 1},
		{-0.7071, 4, "CCW", 0, 53},
		{-0.7071, 5, "CW", 0, 53},
		{-0.7071, 6, "CCW", 0, 42},
		{-0.7071, 7, "CW", 0, 42},
		{1.0249, 0, "CW", 2, 3},
		{1.0249, 1, "CCW", 2, 3},
		{1.0249, 2, "CW", 1, 28},
		{1.0249, 3, "CCW", 1, 28},
		{1.0249, 4, "CW", 1, 17},
		{1.0249, 5, "CCW", 1, 17},
		{1.0249, 6, "CW", 1, 1},
		{1.0249, 7, "CCW", 1, 1},
		{0.2125, 0, "CW", 0, 26},
		{0.2125, 1, "CCW", 0, 26},
		{0.2125, 2, "CW", 0, 18},
		{0.2125, 3, "CCW", 0, 18},
		{0.2125, 4, "CW", 0, 16},
		{0.2125, 5, "CCW", 0, 16},
		{0.2125, 6, "CW", 0, 13},
		{0.2125, 7, "CCW", 0, 13},
		{-0.0125, 0, "CCW", 0, 2},
		{-0.0125, 1, "CW", 0, 2},
		{-0.0125, 2, "CCW", 0, 1},
		{-0.0125, 3, "CW", 0, 1},
		{-0.0125, 4, "CCW", 0, 1},
		{-0.0125, 5, "CW", 0, 1},
		{-0.0125, 6, "CCW", 0, 1},
		{-0.0125, 7, "CW", 0, 1},
		{0.00875, 0, "CW", 0, 1},
		{0.00875, 1, "CCW", 0, 1},
		{0.00875, 2, "CW", 0, 1},
		{0.00875, 3, "CCW", 0, 1},
		{0.00875, 4, "CW", 0, 1},
		{0.00875, 5, "CCW", 0, 1},
		{0.00875, 6, "CW", 0, 1},
		{0.00875, 7, "CCW", 0, 1}}
	for _, c := range cases {
		sign, turns, minutes := screwAdjust(c.diff, c.thread)
		if sign != c.sign || turns != c.turns || minutes != c.minutes {
			t.Errorf("%v thread %d: %s %02d:%02d, want %s %02d:%02d", c.diff, c.thread, sign, turns, minutes,
				c.sign, c.turns, c.minutes)
		}
	}
}
